//----------------------------------------------------------------//
// Private Function:   ostream << Link                            //
//----------------------------------------------------------------//


ostream &operator<<(ostream &stream, Link const &S)
{
  stream << "Link " << S.id_ 
	 << " : capa = " 
	 << S.capa_; 

  return stream;
}



//----------------------------------------------------------------//
// Private Function:   istream >> Link                            //
//----------------------------------------------------------------//

istream &operator>>(istream &stream, Link &x)
{
  return
    (
     stream >> x.id_ 
     >> x.capa_ 
     );
}



